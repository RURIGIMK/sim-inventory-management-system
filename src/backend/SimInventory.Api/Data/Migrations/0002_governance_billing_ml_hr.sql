ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "Department" varchar(120) NULL;

ALTER TABLE "Employees" ADD COLUMN IF NOT EXISTS "UpdatedAt" timestamptz NULL;
ALTER TABLE "Employees" ADD COLUMN IF NOT EXISTS "LastSyncedAt" timestamptz NULL;
ALTER TABLE "Employees" ADD COLUMN IF NOT EXISTS "Source" varchar(40) NOT NULL DEFAULT 'seed';

-- Who performed a custody action must be a real application user. Deferred so a user
-- and the event that records their creation can be written in one transaction.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Assignments_Users_AssignedByUserId') THEN
        ALTER TABLE "Assignments" ADD CONSTRAINT "FK_Assignments_Users_AssignedByUserId"
            FOREIGN KEY ("AssignedByUserId") REFERENCES "Users" ("Id") ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Assignments_Users_ReturnedByUserId') THEN
        ALTER TABLE "Assignments" ADD CONSTRAINT "FK_Assignments_Users_ReturnedByUserId"
            FOREIGN KEY ("ReturnedByUserId") REFERENCES "Users" ("Id") ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_AuditEvents_Users_ActorUserId') THEN
        ALTER TABLE "AuditEvents" ADD CONSTRAINT "FK_AuditEvents_Users_ActorUserId"
            FOREIGN KEY ("ActorUserId") REFERENCES "Users" ("Id") ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS "SimCostRecords" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SimId" integer NOT NULL REFERENCES "Sims" ("Id") ON DELETE RESTRICT,
    "Period" date NOT NULL CHECK (EXTRACT(DAY FROM "Period") = 1),
    "Amount" numeric(12,2) NOT NULL CHECK ("Amount" >= 0),
    "DataUsageMb" integer NULL CHECK ("DataUsageMb" IS NULL OR "DataUsageMb" >= 0),
    "VoiceMinutes" integer NULL CHECK ("VoiceMinutes" IS NULL OR "VoiceMinutes" >= 0),
    "Source" varchar(40) NOT NULL CHECK ("Source" IN ('operator_invoice', 'synthetic')),
    "SyntheticScenario" varchar(60) NULL,
    "ImportBatchId" uuid NULL,
    "ImportedByUserId" uuid NULL REFERENCES "Users" ("Id") ON DELETE RESTRICT,
    "ImportedAt" timestamptz NOT NULL,
    CONSTRAINT "CK_SimCostRecords_ScenarioOnlyForSynthetic"
        CHECK ("SyntheticScenario" IS NULL OR "Source" = 'synthetic')
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SimCostRecords_SimId_Period" ON "SimCostRecords" ("SimId", "Period");
CREATE INDEX IF NOT EXISTS "IX_SimCostRecords_Period" ON "SimCostRecords" ("Period");

CREATE TABLE IF NOT EXISTS "ModelVersions" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Version" varchar(60) NOT NULL,
    "Algorithm" varchar(80) NOT NULL,
    "Status" varchar(20) NOT NULL CHECK ("Status" IN ('candidate', 'active', 'retired')),
    "TrainedAt" timestamptz NOT NULL,
    "TrainingRows" integer NOT NULL,
    "LabelledRows" integer NOT NULL,
    "LabelSource" varchar(60) NOT NULL,
    "DatasetSha256" varchar(64) NOT NULL,
    "FeaturesJson" text NOT NULL,
    "MetricsJson" text NOT NULL,
    "Artifact" bytea NOT NULL,
    "ArtifactSha256" varchar(64) NOT NULL,
    "GitCommit" varchar(64) NULL,
    "RegisteredAt" timestamptz NOT NULL,
    "ActivatedAt" timestamptz NULL,
    "ActivatedByUserId" uuid NULL REFERENCES "Users" ("Id") ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ModelVersions_Version" ON "ModelVersions" ("Version");
-- At most one active model at any time.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ModelVersions_SingleActive" ON "ModelVersions" ("Status") WHERE "Status" = 'active';

CREATE TABLE IF NOT EXISTS "AnomalyScores" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ModelVersionId" integer NOT NULL REFERENCES "ModelVersions" ("Id") ON DELETE RESTRICT,
    "SimId" integer NOT NULL REFERENCES "Sims" ("Id") ON DELETE RESTRICT,
    "Period" date NOT NULL,
    "Score" double precision NOT NULL,
    "IsFlagged" boolean NOT NULL,
    "ReasonsJson" text NOT NULL,
    "ScoredAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_AnomalyScores_ModelVersionId_SimId_Period" ON "AnomalyScores" ("ModelVersionId", "SimId", "Period");

CREATE TABLE IF NOT EXISTS "AnomalyReviews" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SimId" integer NOT NULL REFERENCES "Sims" ("Id") ON DELETE RESTRICT,
    "Period" date NOT NULL,
    "Decision" varchar(20) NOT NULL CHECK ("Decision" IN ('confirmed', 'dismissed')),
    "Note" varchar(1000) NOT NULL,
    "FlaggedBy" varchar(20) NOT NULL CHECK ("FlaggedBy" IN ('none', 'rule', 'model', 'both')),
    "ModelVersionId" integer NULL REFERENCES "ModelVersions" ("Id") ON DELETE RESTRICT,
    "ReviewedByUserId" uuid NOT NULL REFERENCES "Users" ("Id") ON DELETE RESTRICT,
    "ReviewedAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_AnomalyReviews_SimId_Period" ON "AnomalyReviews" ("SimId", "Period");

CREATE TABLE IF NOT EXISTS "EmployeeSyncRuns" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Source" varchar(40) NOT NULL,
    "Mode" varchar(20) NOT NULL,
    "StartedAt" timestamptz NOT NULL,
    "FinishedAt" timestamptz NULL,
    "Received" integer NOT NULL,
    "Created" integer NOT NULL,
    "Updated" integer NOT NULL,
    "Deactivated" integer NOT NULL,
    "Unchanged" integer NOT NULL,
    "Rejected" integer NOT NULL,
    "Outcome" varchar(30) NOT NULL,
    "ErrorsJson" text NOT NULL,
    "TriggeredBy" varchar(320) NOT NULL
);
